-- 4. residents --------------------------------------------------------
create table public.residents (
  id                  uuid primary key default gen_random_uuid(),
  profile_id          uuid unique references public.profiles (id) on delete set null,
  purok_id            smallint not null references public.puroks (id),
  first_name          text not null check (char_length(first_name) between 1 and 60),
  middle_name         text check (middle_name is null or char_length(middle_name) <= 60),
  last_name           text not null check (char_length(last_name) between 1 and 60),
  suffix              text check (suffix is null or char_length(suffix) <= 10),
  birth_date          date not null check (birth_date > date '1900-01-01' and birth_date <= current_date),
  sex                 text not null check (sex in ('male','female')),
  civil_status        text not null check (civil_status in ('single','married','widowed','separated','annulled')),
  street_address      text not null check (char_length(street_address) between 3 and 200),
  contact_no          text check (contact_no is null or contact_no ~ '^(09|\+639)[0-9]{9}$'),
  email               text check (email is null or email ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  occupation          text check (occupation is null or char_length(occupation) <= 100),
  resident_since      date not null check (resident_since <= current_date),
  is_registered_voter boolean not null default false,
  verification_status text not null default 'unverified'
                      check (verification_status in ('unverified','pending','verified','rejected')),
  verified_by         uuid references public.profiles (id) on delete set null,
  verified_at         timestamptz,
  status              text not null default 'active'
                      check (status in ('active','moved_out','deceased','inactive')),
  created_by          uuid references public.profiles (id) on delete set null,
  created_at          timestamptz not null default now(),
  updated_at          timestamptz not null default now(),
  check (resident_since >= birth_date)
);
-- One person per name + birth date
create unique index residents_identity_uniq
  on public.residents (lower(last_name), lower(first_name), lower(coalesce(middle_name, '')), birth_date);
create index residents_purok_idx on public.residents (purok_id);
create index residents_verification_idx on public.residents (verification_status);
create index residents_last_name_idx on public.residents (lower(last_name));

