create table public.document_requests (
  id               uuid primary key default gen_random_uuid(),
  control_no       text not null unique,
  resident_id      uuid not null references public.residents (id) on delete restrict,
  document_type_id smallint not null references public.document_types (id) on delete restrict,
  purpose_id       smallint not null references public.purposes (id) on delete restrict,
  purpose_details  text check (purpose_details is null or char_length(purpose_details) <= 255),
  copies           smallint not null default 1 check (copies between 1 and 10),
  extra_details    jsonb not null default '{}'::jsonb check (jsonb_typeof(extra_details) = 'object'),
  channel          text not null check (channel in ('online','walk_in')),
  fee_amount       numeric(10,2) not null default 0 check (fee_amount >= 0),
  fee_waived       boolean not null default false,
  waiver_reason    text,
  status           text not null default 'pending'
                   check (status in ('pending','under_review','for_payment','processing','for_approval',
                                     'ready_for_release','released','rejected','cancelled')),
  rejection_reason text,
  requested_by     uuid not null references public.profiles (id),
  submitted_at     timestamptz not null default now(),
  released_at      timestamptz,
  released_to      text check (released_to is null or char_length(released_to) between 2 and 120),
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  check (not fee_waived or char_length(coalesce(waiver_reason, '')) between 10 and 500),
  check (status <> 'rejected' or char_length(coalesce(rejection_reason, '')) between 10 and 500),
  check (status <> 'released' or (released_at is not null and released_to is not null))
);
-- One open request per document type per resident
