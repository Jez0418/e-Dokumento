-- Control number <PREFIX>-<YEAR>-<000001> -------------------------------
create or replace function public.set_request_control_no()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_prefix text;
begin
  if new.control_no is null or new.control_no = '' then
    select s.value #>> '{}' into v_prefix from public.system_settings s where s.key = 'control_prefix';
    v_prefix := upper(coalesce(nullif(v_prefix, ''), 'REQ'));
    new.control_no := v_prefix || '-' || to_char(now() at time zone 'Asia/Manila', 'YYYY') || '-'
                      || lpad(nextval('public.request_control_seq')::text, 6, '0');
  end if;
  return new;
end;
$$;

create trigger document_requests_control_no
  before insert on public.document_requests
  for each row execute function public.set_request_control_no();

-- Listing views (not tables). security_invoker = on makes them obey the caller's RLS.
create or replace view public.request_list with (security_invoker = on) as
select
  d.id, d.control_no, d.status, d.channel, d.copies, d.fee_amount, d.fee_waived,
  d.submitted_at, d.released_at, d.updated_at,
  d.resident_id, r.first_name, r.last_name,
  concat_ws(' ', r.first_name, r.middle_name, r.last_name, r.suffix) as resident_name,
  r.purok_id, pk.name as purok_name,
  d.document_type_id, t.name as document_type, t.code as document_code, t.processing_days,
  d.purpose_id, pu.name as purpose,
  (d.status in ('pending','under_review','processing','for_approval')
     and d.submitted_at + make_interval(days => t.processing_days::integer) < now()) as is_overdue,
  lower(d.control_no || ' ' || concat_ws(' ', r.first_name, r.middle_name, r.last_name)) as search_text
from public.document_requests d
join public.residents r on r.id = d.resident_id
join public.document_types t on t.id = d.document_type_id
join public.purposes pu on pu.id = d.purpose_id
join public.puroks pk on pk.id = r.purok_id;

create or replace view public.payment_list with (security_invoker = on) as
select
  p.id, p.or_number, p.amount, p.method, p.reference_no, p.status, p.paid_at,
  p.void_reason, p.voided_at, p.received_by, pr.full_name as received_by_name,
  p.request_id, d.control_no, d.status as request_status, t.name as document_type,
  concat_ws(' ', r.first_name, r.last_name) as resident_name,
  lower(p.or_number || ' ' || d.control_no || ' ' || r.first_name || ' ' || r.last_name) as search_text
from public.payments p
join public.document_requests d on d.id = p.request_id
join public.residents r on r.id = d.resident_id
join public.document_types t on t.id = d.document_type_id
left join public.profiles pr on pr.id = p.received_by;

create or replace view public.issued_document_list with (security_invoker = on) as
select
  i.id, i.document_no, i.verification_code, i.issued_at, i.valid_until, i.status, i.print_count,
  i.revoked_reason, i.request_id, d.control_no, d.status as request_status,
  d.document_type_id, t.name as document_type,
  concat_ws(' ', r.first_name, r.last_name) as resident_name,
  lower(i.document_no || ' ' || d.control_no || ' ' || r.first_name || ' ' || r.last_name) as search_text
from public.issued_documents i
join public.document_requests d on d.id = i.request_id
join public.residents r on r.id = d.resident_id
join public.document_types t on t.id = d.document_type_id;
